# -*- coding: utf-8 -*-
"""兄弟デッキが同じ弾コード・同じ番号を使う商品の **枝番** (2026-09-04 新設).

## 何のためか

公式は兄弟デッキに **同じ弾コードと同じ番号**を振る。

    スターターセットV 雷 / 草 / 炎 / 水 / 闘   … 全部 `SA` の `001/024` から始まる
    スターターセットVMAX リザードン / オーロンゲ … 全部 `SCS` の `001/021`
    30枚デッキ対戦set ミュウツー / ゲノセクト   … 全部 `MG`

catalog の鍵は `SA-001` 一つなので、**先に入った1デッキしか持てない**。
実測 2026-09-04: これで 142枚が構造的に入らず、しかも
`lookup_pokemon("...VMAX CHARIZARD", "001")` が **オーロンゲのアブソル**を返していた
(ID 一致だけで名前を見ていなかったため)。

## 決めたこと

**後から入れる方に枝番を付ける** (`SCS-C-001`)。**先に入っている方は動かさない**
(既に出品に使われている KEY を変えない)。前例: `S8a-G` (25周年ゴールデンボックス) /
`DPt-GBpi-001` (DPt ギフトボックス ピカチュウ)。

★ここに無い商品で衝突したら **入れずに報告する** (fail-closed)。
  勝手に枝番を作ると、出品くんが引けない ID が増える。

## 出品くんが引けること (ここが本題)

PSA のラベルには商品名が入る (`STARTER SET V GRASS` 等) ので、
`integrations/psa_to_csv.py` の `extract_set_code_from_brand_pokemon()` に
**同じ枝番を返す keyword** を入れてある。ラベル → 枝番 → ID が1本で通る。
"""
from __future__ import annotations

# 収録商品名 (公式 set_name_official) → 枝番。値が "" の商品は **枝番なし** (先に入っている方)。
DECK_SUFFIX: dict[str, str] = {
    # スターターセットV (SA) — 雷が先に入っている
    "スターターセットV 雷": "",
    "スターターセットV 草": "G",
    "スターターセットV 炎": "R",
    "スターターセットV 水": "W",
    "スターターセットV 闘": "F",
    # スターターセットVMAX (SCS) — オーロンゲが先に入っている
    "スターターセットVMAX オーロンゲ": "",
    "スターターセットVMAX リザードン": "C",
    "スターターセットVMAX フシギバナ": "V",
    "スターターセットVMAX カメックス": "B",
    # 対戦スターターパック「ギラティナVSディアルガ」(DPs-S) — ディアルガが先に入っている。
    #   ★こちらは MG と違い **公式の収録商品名にデッキ名が入っている**ので分けられる。
    #   番号のふり方も別 (ギラティナ側 011=モンスターボール / ディアルガ側 012=モンスターボール)
    #   なので、共通のカードも含めて **14枚すべて**を枝番付きで持つ。
    "ポケモンカードゲームDP 対戦スターターパック「ギラティナVSディアルガ」(ディアルガデッキ)": "",
    "ポケモンカードゲームDP 対戦スターターパック「ギラティナVSディアルガ」(ギラティナデッキ)": "G",
    # ★30枚デッキ対戦set (MG) は **表に入れない** (2026-09-04)。
    #   ミュウツー側とゲノセクト側で **公式の収録商品名が同じ**なので、
    #   商品名では2デッキを分けられない。表に "" を置くと「衝突なし」と判定され、
    #   後から来たデッキが **先の行を上書きする** (実際に MG-001 が ミュウツー →
    #   モンジャラ に化けた。8/31 のバックアップから戻した)。
    #   表に無い = 衝突したら入れずに止まる、が正しい振る舞い。
    # XY コードは複数商品が共用している (THE BEST OF XY が最多で、これが枝番なし)。
    # 番号が衝突する商品にだけ枝番を振る。
    "ハイクラスパック「THE BEST OF XY」": "",
    "エクストラバトルの日": "",
    "「エクストラレギュレーションBOX」": "ERB",
    "ポケモンカードゲーム サン&ムーン デッキビルドBOX「ウルトラサン」": "US",
    "ポケモンカードゲーム サン&ムーン デッキビルドBOX「ウルトラムーン」": "UM",
    # M-P (メガ プロモ) — プロモカードパック第1弾 が先に入っている
    "ポケモンカードゲーム MEGA プロモカードパック第1弾": "",
    # ★マクドナルドは **引き当てを止めてある** (CLAUDE.md / psa_to_csv の
    #   `MCDONALDS` → None)。行は入れてよいが、PSA からは引かない。
    "マクドナルド「ハッピーセット2025」": "MCD",
}


def deck_suffix(set_name_official: str | None) -> str | None:
    """その商品の枝番。表に無ければ None (= 呼び出し側で fail-closed)."""
    if not set_name_official:
        return None
    return DECK_SUFFIX.get(set_name_official.strip())


def apply_suffix(product_id: str, suffix: str) -> str:
    """`SCS-001` + `C` → `SCS-C-001` (番号は末尾のまま = 券面番号で引ける形を保つ)."""
    if not suffix:
        return product_id
    head, _, num = product_id.rpartition("-")
    return f"{head}-{suffix}-{num}" if head else product_id
